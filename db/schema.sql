-- 2.1 Bump version + updated_at on every update (optimistic locking support)
create or replace function public.pp_touch_row()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.version    := old.version + 1;
  new.updated_at := now();
  return new;
end;
$$;

